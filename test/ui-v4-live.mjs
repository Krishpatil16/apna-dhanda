
import { chromium } from "playwright-core";
const BASE = process.env.BASE, OUT = process.env.OUT; const ORD = JSON.parse(process.env.ORD);
const exe = `${process.env.HOME}/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome`;
const b = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: "hi-IN" });
const errors = []; const log = {};
const page = await ctx.newPage();
page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", e => errors.push("pageerror: " + e.message));
await page.goto(BASE + "/", { waitUntil: "domcontentloaded" });
await page.evaluate(o => localStorage.setItem("ak_orders", JSON.stringify(o)), ORD);
await page.goto(BASE + "/", { waitUntil: "networkidle" });
await page.waitForSelector(".card");
await page.fill("#dlIn", "490023"); await page.click("#dlForm button"); await page.waitForTimeout(1500);
log.delivery = await page.locator("#delivery").innerText();
log.recent = await page.locator("#recent .mini-card").count();
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: `${OUT}/v4-home-delivery-check.png` });
await page.selectOption("#sort", "price_asc"); await page.waitForTimeout(300); log.sortFirst = await page.locator(".card h3").first().innerText(); await page.selectOption("#sort", "");
await page.locator(".card .tile").first().click(); await page.waitForTimeout(400); log.similar = await page.locator(".sim-h + .hscroll .mini-card").count(); await page.click("#sheetClose");
await page.goto(BASE + "/track", { waitUntil: "networkidle" }); await page.waitForTimeout(1200);
log.reorderBtns = await page.locator("[data-reorder]").count();
await page.locator("[data-reorder]").first().click(); await page.waitForTimeout(1200);
log.roBox = await page.locator("#roBox").innerText().catch(() => "none");
await page.evaluate(() => window.scrollTo(0, 0)); await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/v4-my-orders-reorder.png` });
await page.goto(BASE + `/track#${ORD[0].code}.${ORD[0].token}`, { waitUntil: "networkidle" }); await page.waitForTimeout(1200);
log.rateForm = await page.locator("#rateF").count();
await page.locator("[data-star='5']").click(); await page.fill("#rc", "Jaldi aaya, saman achha tha (test rating)");
await page.locator("#rateF").scrollIntoViewIfNeeded(); await page.waitForTimeout(200);
await page.screenshot({ path: `${OUT}/v4-rating-before.png` });
await page.locator("#rateF button[type=submit]").click(); await page.waitForTimeout(1500);
log.rated = await page.locator(".rate-box").innerText().catch(() => "none");
await page.locator(".rate-box").scrollIntoViewIfNeeded(); await page.evaluate(() => window.scrollBy(0, -260));
await page.screenshot({ path: `${OUT}/v4-rating.png` });
console.log(JSON.stringify({log, errors}, null, 1));
await b.close();
